function resolveKey(id: string, custom?: boolean): string | undefined {
  if (custom === true) return "custom";
  const lowered = id.toLowerCase();
  if (ALIAS[lowered] !== undefined) return ALIAS[lowered];
  if (lowered.startsWith("kimi") || lowered.includes("moonshot")) return "kimi";
  if (lowered.includes("qwen") || lowered.includes("dashscope")) return "qwen";
  if (lowered.includes("openai") || lowered.includes("codex")) return "openai";
  if (lowered.includes("claude") || lowered.includes("anthropic")) return "anthropic";
  if (lowered.includes("grok")) return "grok";
  if (lowered.startsWith("xai")) return "xai";
  if (lowered.includes("deepseek")) return "deepseek";
  if (lowered.includes("glm") || lowered.includes("zhipu")) return "zhipu";
  if (lowered.startsWith("zai")) return "zai";
  if (lowered.includes("minimax")) return "minimax";
  if (lowered.includes("doubao") || lowered.includes("volc") || lowered.includes("byte")) return "doubao";
  if (lowered.includes("hunyuan") || lowered.includes("tencent")) return "hunyuan";
  if (lowered.includes("spark") || lowered.includes("ifly") || lowered.includes("xfyun")) return "spark";
  if (lowered.includes("google") || lowered.includes("gemini") || lowered.includes("vertex")) return "google";
  if (lowered.includes("groq")) return "groq";
  if (lowered.includes("openrouter")) return "openrouter";
  if (lowered.includes("mistral")) return "mistral";
  if (lowered.includes("firework")) return "fireworks";
  if (lowered.includes("hugging")) return "huggingface";
  if (lowered.includes("together")) return "together";
  if (lowered.includes("nvidia")) return "nvidia";
  if (lowered.includes("cerebras")) return "cerebras";
  if (lowered.includes("perplex")) return "perplexity";
  if (lowered.includes("cohere")) return "cohere";
  if (lowered.includes("github") || lowered.includes("copilot")) return "github";
  if (lowered.includes("bedrock") || lowered.includes("amazon") || lowered.includes("aws")) return "aws";
  if (lowered.includes("azure")) return "azure";
  return undefined;
}

export function ProviderLogo({ id, size, custom }: { id: string; size: number; custom?: boolean }) {
  const key = resolveKey(id, custom);
  const draw = key === undefined ? undefined : LOGOS[key];
  if (draw !== undefined) return <>{draw(size)}</>;
  const label = id.split(/[-_]/).filter(Boolean).slice(0, 2).map((part) => part[0]?.toUpperCase() ?? "").join("") || "?";
  return (
    <span className="dshM-fallbackIcon" style={{ width: size, height: size, fontSize: Math.max(8, Math.floor(size * 0.42)) }} aria-hidden="true">
      {label}
    </span>
  );
}
